/** строка в панели «Настройки»: переключатель, название и пояснение под ним */
export function optRow(key, checked, onchange, { disabled } = {}) {
  const x = HELP[key] || [key, ''];
  return h('label', { class: 'opt-row' + (disabled ? ' off' : '') }, h('span', { class: 'check' }, h('input', { type: 'checkbox', checked: !!checked, disabled: !!disabled, onchange: e => onchange(e.target.checked) })),
    h('span', { class: 'ot' }, h('b', {}, x[0]), x[1] ? h('small', {}, x[1]) : null));
}
/** строка в панели «Настройки» с другим элементом справа (список, кнопка) */
export function ctlRow(key, ctl, { disabled } = {}) {
  const x = HELP[key] || [key, ''];
  return h('div', { class: 'opt-row ctl' + (disabled ? ' off' : '') }, h('span', { class: 'ot' }, h('b', {}, x[0]), x[1] ? h('small', {}, x[1]) : null), ctl);
}
/** значок «?» рядом с настройкой: щелчок — окно с пояснением */
export function tip(key) {
  const x = HELP[key]; if (!x) return null;
  return h('button', { class: 'tip', type: 'button', 'aria-label': `Что такое «${x[0]}»`, title: x[1], onclick: e => { e.preventDefault(); e.stopPropagation(); explain(key); } }, '?');
}
export const explain = key => { const [t, text] = HELP[key]; return dialog(close => h('div', { class: 'dlg' }, h('h2', {}, t), h('p', { style: { margin: 0 } }, text),
  h('div', { class: 'dlg-foot' }, h('button', { class: 'btn primary', onclick: () => close(true) }, 'Понятно')))); };

